void DungeonGlacier::fillWithEnemies()
{
	for (int i = 0; i < 15; i++)
	{
		for (int j = 0; j < 15; j++)
		{
			if (this->getDungeonMap()[(this->getDungeonRoom() - 1)][i][j] == ' ')
			{
				int spawnChance = (rand() % 100) + 1;
				if (spawnChance > 74)
				{
					this->setPosition((this->getDungeonRoom() - 1), i, j, '!');
				}
			}
		}
	}
}